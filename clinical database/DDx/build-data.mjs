// Bundles regions.json and symptoms/*.json into ddx-data.mjs, the module the differential diagnosis tab imports.
// Every order link must name an existing order-tab chapter slug and condition.
// Run after editing: node "clinical database/DDx/build-data.mjs"
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { loadChapters } from '../JustDoIt/build-data.mjs';

const here = new URL('./', import.meta.url);
const strings = value => Array.isArray(value) && value.every(entry => typeof entry === 'string' && entry.trim());

export async function loadRegions() {
  const regions = JSON.parse(await readFile(new URL('regions.json', here), 'utf8'));
  for (const region of regions) for (const key of ['id', 'name', 'en', 'icon']) if (!region[key]) throw new Error(`regions.json: ${region.id || '?'} missing ${key}`);
  if (new Set(regions.map(region => region.id)).size !== regions.length) throw new Error('regions.json: duplicate id');
  return regions;
}

// Order links are [chapter slug, condition name]; both must exist in the order tab.
function checkOrders(orders, chapters, where) {
  if (orders === undefined) return;
  if (!Array.isArray(orders)) throw new Error(`${where}: orders must be a list`);
  for (const link of orders) {
    if (!Array.isArray(link) || link.length !== 2) throw new Error(`${where}: bad order link ${JSON.stringify(link)}`);
    const chapter = chapters.find(entry => entry.slug === link[0]);
    if (!chapter) throw new Error(`${where}: unknown order chapter "${link[0]}"`);
    if (!chapter.items.some(item => item.name === link[1])) throw new Error(`${where}: "${link[1]}" not found in order chapter ${link[0]}`);
  }
}

function checkDetails(entry, where) {
  for (const key of ['pe', 'scores', 'flags']) if (entry[key] !== undefined && !strings(entry[key])) throw new Error(`${where}: ${key} must be a list of text`);
}

export async function loadSymptoms(regions, chapters) {
  const regionIds = new Set(regions.map(region => region.id));
  const names = (await readdir(new URL('symptoms/', here))).filter(name => name.endsWith('.json')).sort();
  const symptoms = [];
  for (const name of names) {
    const list = JSON.parse(await readFile(new URL(`symptoms/${name}`, here), 'utf8'));
    for (const symptom of list) {
      const where = `symptoms/${name} · ${symptom.id || '?'}`;
      for (const key of ['id', 'name', 'en']) if (!symptom[key]) throw new Error(`${where}: missing ${key}`);
      if (!strings(symptom.regions) || symptom.regions.some(id => !regionIds.has(id))) throw new Error(`${where}: unknown region`);
      if (symptom.aliases !== undefined && !strings(symptom.aliases)) throw new Error(`${where}: aliases must be a list of text`);
      if (!symptom.first) throw new Error(`${where}: missing first`);
      checkDetails(symptom.first, `${where} · first`);
      checkOrders(symptom.first.orders, chapters, `${where} · first`);
      if (!Array.isArray(symptom.groups) || !symptom.groups.length) throw new Error(`${where}: no groups`);
      for (const group of symptom.groups) {
        if (!group.title || !Array.isArray(group.dx) || !group.dx.length) throw new Error(`${where}: empty group "${group.title}"`);
        for (const dx of group.dx) {
          const at = `${where} · ${dx.name || '?'}`;
          if (!dx.name || !dx.en || !dx.clues) throw new Error(`${at}: missing name, en or clues`);
          checkDetails(dx, at);
          checkOrders(dx.orders, chapters, at);
        }
      }
      symptoms.push(symptom);
    }
  }
  if (new Set(symptoms.map(symptom => symptom.id)).size !== symptoms.length) throw new Error('symptoms: duplicate id');
  const empty = regions.filter(region => !symptoms.some(symptom => symptom.regions.includes(region.id))).map(region => region.id);
  if (empty.length) throw new Error(`regions without symptoms: ${empty.join(', ')}`);
  return symptoms;
}

export function renderModule(regions, symptoms) {
  return '// Generated by build-data.mjs from regions.json and symptoms/*.json. Edit those files, not this one.\n'
    + `export const DDX_REGIONS = ${JSON.stringify(regions)};\n`
    + `export const DDX_SYMPTOMS = ${JSON.stringify(symptoms)};\n`;
}

export async function loadAll() {
  const regions = await loadRegions();
  return { regions, symptoms: await loadSymptoms(regions, await loadChapters()) };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { regions, symptoms } = await loadAll();
  await writeFile(new URL('ddx-data.mjs', here), renderModule(regions, symptoms));
  const count = symptoms.reduce((sum, symptom) => sum + symptom.groups.reduce((total, group) => total + group.dx.length, 0), 0);
  console.log(`Wrote ddx-data.mjs: ${regions.length} regions, ${symptoms.length} symptoms, ${count} diagnoses.`);
}
